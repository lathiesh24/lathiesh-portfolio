import { readFileSync, writeFileSync } from 'node:fs';

const draft = JSON.parse(readFileSync(new URL('../content/portfolio-draft.json', import.meta.url), 'utf8'));
const profile = Object.fromEntries(['introduction', 'about', 'skills', 'education', 'contact'].map(key => [key, draft[key]]));
const experience = draft.experience.map(role => ({
  company: role.company,
  role: role.company === 'Klisme' ? 'Software Developer Intern' : role.role,
  period: role.period,
  location: role.location,
  kind: role.employment ?? 'Part-time → Full-time',
  description: role.summary,
  current: role.company === 'Corvus',
  contributions: role.contributions ?? [],
  technologies: role.confirmedTechnologies ?? [],
  stackGroups: role.stackGroups ?? [],
  toolNotes: role.toolNotes ?? {},
  links: role.links ?? [],
  phases: (role.phases ?? []).map(phase => `${phase.period} · ${phase.employment}`),
}));
const caseStudyContent = Object.fromEntries(draft.projects.map((project, i) => [
  ['corvus', 'tia', 'saramsa', 'nifo'][i],
  {
    description: project.summary,
    problem: project.problem,
    contributions: project.myContribution,
    stack: project.stack,
    ...(project.links[0] ? { link: project.links[0].url, linkLabel: project.links[0].label } : {}),
  },
]));
const source = `// Generated by scripts/sync-content.mjs. Only visitor-facing content belongs here.\n\nexport const profile = ${JSON.stringify(profile, null, 2)};\n\nexport const experience = ${JSON.stringify(experience, null, 2)};\n\nexport const caseStudyContent: Record<string, { description: string; problem: string; contributions: string[]; stack: string[]; link?: string; linkLabel?: string }> = ${JSON.stringify(caseStudyContent, null, 2)};\n`;
writeFileSync(new URL('../src/lib/profile.ts', import.meta.url), source);
console.log('Synced public profile, four employers, and four case studies. Editorial notes and college projects are excluded.');
